def make_facility_id():
    ts = int(time.time() * 1000)
    return f"{ts:013x}-{uuid.uuid4().hex[:12]}"


def seed(env: str, aws_region: str):
    table_name = f"HealthTrack-Facilities-{env}"
    ddb = boto3.resource("dynamodb", region_name=aws_region)
    table = ddb.Table(table_name)

    seeded = 0
    skipped = 0

    for facility in FACILITIES:
        item = dict(facility)
        item["facility_id"] = make_facility_id()
        item["created_at"] = int(time.time() * 1000)
        # Ensure capabilities is a set for DynamoDB StringSet
        if "capabilities" in item and isinstance(item["capabilities"], set) and item["capabilities"]:
            pass  # already a set
        elif "capabilities" in item:
            item["capabilities"] = set(item["capabilities"]) if item["capabilities"] else None

        try:
            table.put_item(
                Item=item,
                ConditionExpression="attribute_not_exists(facility_id)",
            )
            seeded += 1
            # Small sleep to avoid ULID collision (time-based IDs)
            time.sleep(0.001)
        except ddb.meta.client.exceptions.ConditionalCheckFailedException:
            skipped += 1

    print(f"Seeded {seeded} facilities, skipped {skipped} (already exist)")


